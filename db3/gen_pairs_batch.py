def build_pair(idx: int, spec: tuple) -> dict:
    (domain, lang, text, prop, rule, tgt, qb, qkey, qexpr, comp,
     result, scale) = spec
    strictness, need_ambig, need_db5 = RULE_CONTRACT[rule]
    q_dir = "lower_bound"
    return {
        "pair_id": "DB3-%04d" % idx,
        "domain": domain,
        "language": lang,
        "requirement_text": text,
        "requirement_structured": {
            "property_id": prop,
            "metric_direction": "bound_below",
            "direction": "bound_below",
            "quantity_bound": qb,
            "quantity_bound_source": "declared",
            "quantity_bound_review": "ok",
            "target_value": tgt,
            "rv_hint": "programmatic_template",
            "constraints": [],
            "ambiguity_flags": [_COND_AMBIG] if need_ambig else [],
        },
        "rule_ids": [rule],
        "info_metric_vector": {
            qkey: {"direction": q_dir, "expr": qexpr,
                   "note": "表驱动生成（%s 域实例）" % domain}
        },
        "worked_example": {
            "setup": text,
            "given": {k: {"value": v, "unit": "as_declared",
                          "is_bridge_constant": False}
                      for k, v in tgt.items()},
            "computation": comp,
            "result": result,
            "reference_scale": scale,
        },
        "metric_rationale": [
            "cross domain rl architecture plan.md §2.3.3 %s" % rule,
            "md/information mechanics derivations.md §1 定理 1.3（Cramér–Rao）"
            if prop == "precision" else
            "md/information mechanics derivations.md（对应规则推导）",
            "%s 域需求（表驱动程序化生成，待人工复核）" % domain,
        ],
        "strictness": strictness,
        "requires_db5_calibration": need_db5,
        "provenance": {
            "source": "AI+drafted",
            "human_review_status": "pending",
            "anchor_eligible": False,
            "review_date": None,
            "reviewer": None,
        },
        "rules_version": "0.2.0",
        "convention_version": "1.0.0",
    }


def main() -> int:
    apply = "--apply" in sys.argv[1:]
    start = None
    if "--start" in sys.argv[1:]:
        start = int(sys.argv[sys.argv.index("--start") + 1])
    lo, hi = 0, len(SPECS)
    if "--slice" in sys.argv[1:]:          # 只生成规格表的一段（防重复生成）
        a, b = sys.argv[sys.argv.index("--slice") + 1].split(":")
        lo, hi = int(a), int(b)
    specs = SPECS[lo:hi]
    existing = sorted(PAIRS.glob("DB3-*.json"))
    next_id = 1
    if existing:
        next_id = max(int(p.stem.split("-")[1]) for p in existing) + 1
    if start is not None:
        next_id = start          # 覆盖既有编号（重生成场景）
    print("=== 表驱动需求对生成%s（%d 条，规格表 %d:%d，起始编号 DB3-%04d）==="
          % ("（已写入）" if apply else "（干跑）", len(specs), lo, hi, next_id))
    for k, spec in enumerate(specs):
        rec = build_pair(next_id + k, spec)
        print("  %s  %-14s %-16s %s" % (rec["pair_id"], spec[0], spec[3],
                                        spec[2][:34]))
        if apply:
            (PAIRS / ("%s.json" % rec["pair_id"])).write_text(
                json.dumps(rec, ensure_ascii=False, indent=2),
                encoding="utf-8")
    if apply:
        print("  已写入 %d 条（human_review_status=pending，待人工复核）"
              % len(SPECS))
    else:
        print("  （干跑结束；加 --apply 写入）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
